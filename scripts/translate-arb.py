def main():
    print("=" * 60)
    print("ARB Translation Merger")
    print("=" * 60)

    en = load_json(EN_PATH)
    zh = load_json(ZH_PATH)

    en_keys = [k for k in en if not k.startswith("@")]
    zh_keys_before = [k for k in zh if not k.startswith("@")]
    print(f"\nEnglish non-metadata keys: {len(en_keys)}")
    print(f"Chinese non-metadata keys BEFORE: {len(zh_keys_before)}")

    missing = [k for k in en_keys if k not in zh]
    print(f"Missing keys: {len(missing)}")

    # Build merged dict
    merged = dict(zh)
    translated = 0
    fallback = 0

    for key in en:
        if key == "@@locale":
            merged[key] = "zh"
            continue

        if key.startswith("@"):
            # Metadata key - copy from English if base key will be present
            base = key[1:]
            if base in merged or base in en:
                if key not in merged:
                    merged[key] = en[key]
            continue

        if key not in merged:
            if key in TRANSLATIONS:
                merged[key] = TRANSLATIONS[key]
                translated += 1
            else:
                merged[key] = en[key]
                fallback += 1
                print(f"  FALLBACK: {key}")

    print(f"\nTranslated: {translated}")
    print(f"Fallback to English: {fallback}")

    # Write output using json.dumps for correct escaping
    with open(ZH_PATH, "w", encoding="utf-8") as f:
        json.dump(merged, f, ensure_ascii=False, indent=2)

    # Verify
    zh_after = load_json(ZH_PATH)
    zh_keys_after = [k for k in zh_after if not k.startswith("@")]
    print(f"\nChinese non-metadata keys AFTER: {len(zh_keys_after)}")
    print(f"Match English: {'YES' if len(zh_keys_after) == len(en_keys) else 'NO'}")

    if len(zh_keys_after) != len(en_keys):
        en_set = set(en_keys)
        zh_set = set(zh_keys_after)
        diff1 = en_set - zh_set
        diff2 = zh_set - en_set
        if diff1:
            print(f"  Still missing: {diff1}")
        if diff2:
            print(f"  Extra: {diff2}")

    print("\nDone!")


if __name__ == "__main__":
    main()
